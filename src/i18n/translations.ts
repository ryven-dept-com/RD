/**
 * Phase 9 — centralized storefront translations.
 *
 * One flat dictionary per language; components resolve labels through the
 * language context (`useT`). Only UI/system text lives here — product
 * names, descriptions, categories, wilayas and CMS content stay exactly as
 * stored by the admin (they are data, not UI strings).
 */

export const LOCALES = ["ar", "fr", "en"] as const;
export type Locale = (typeof LOCALES)[number];

export const DEFAULT_LOCALE: Locale = "en";

export const LOCALE_COOKIE = "rd-locale";

export function isLocale(value: unknown): value is Locale {
  return LOCALES.includes(value as Locale);
}

export function localeDir(locale: Locale): "rtl" | "ltr" {
  return locale === "ar" ? "rtl" : "ltr";
}

/**
 * BCP-47 tag used for Intl date formatting. Arabic pins the Gregorian
 * calendar with Latin digits (Algerian e-commerce convention) so review
 * dates stay deterministic across ICU builds.
 */
export function localeTag(locale: Locale): string {
  switch (locale) {
    case "fr":
      return "fr-FR";
    case "ar":
      return "ar-DZ-u-ca-gregory-nu-latn";
    default:
      return "en-US";
  }
}

/** Resolve a persisted cookie/header value to a supported locale. */
export function resolveLocale(value: string | undefined | null): Locale {
  const v = (value ?? "").trim().toLowerCase();
  return isLocale(v) ? v : DEFAULT_LOCALE;
}

